/// 带 BCP47 子标签的繁体（zh-TW/zh-Hant/zho-Hant 等）。
/// normalize() 的「前两位截取」会把 zh-* 都截成 "zh"，因此带标签繁体必须
/// 在截取前特判（见函数体）。
const HANT_TAGS: &[&str] = &["zh-tw", "zh-hant", "zh_hant", "zho-hant", "zh-hk", "zh-mo"];

/// 规范化为 rumi 内部码（ISO 639-1 两位码子集 + 繁体 "zht"）。
/// 其余写法：小写后取前两位（"JA"→"ja"，"en-US"→"en"）；
/// 截不出两位字母码的未知输入原样返回小写（不报错，交由上层按未知语言处理）。
pub fn normalize(lang: &str) -> String {
    let s = lang.trim().to_lowercase();
    if HANT_TAGS.contains(&s.as_str()) {
        return "zht".to_string();
    }
    if let Some((_, code)) = ALIASES.iter().find(|(k, _)| *k == s.as_str()) {
        return (*code).to_string();
    }
    let mut chars = s.chars();
    match (chars.next(), chars.next()) {
        (Some(a), Some(b)) if a.is_ascii_alphabetic() && b.is_ascii_alphabetic() => {
            format!("{a}{b}")
        }
        _ => s,
    }
}

